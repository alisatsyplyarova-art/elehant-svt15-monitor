// Настройки, не зависящие от платы. Пины и память: monitor_boards.h
#pragma once
#include "monitor_boards.h"   // платы идут первыми: они могут задать размер и поворот встроенного дисплея

// ---- Самотест дисплея при старте (LCD5110: перебор контраста ~8 сек) ----
#define SVT_SELFTEST 1

// ---- Безопасный режим Wi-Fi ----
// 1 = домашняя сеть (STA) отключена на время работы, остаётся только точка доступа.
// Значение в памяти не меняется. Нужно, если из-за STA не открывается WEB.
#define SVT_FORCE_STA_OFF 0

// ---- BLE-библиотека ----
// 0 = встроенная (BLEDevice), 1 = NimBLE-Arduino версии 2.x (Library Manager: "NimBLE-Arduino",
// нужно ядро ESP32 3.x). NimBLE занимает заметно меньше флеш-памяти и ОЗУ.
// Если не собирается (нет библиотеки или другая версия), поставить 0.
#define SVT_BLE_NIMBLE 1
// Окно приёма NimBLE: интервал и окно сканирования, мс (окно не больше интервала; 60% как у встроенной библиотеки)
#define SVT_BLE_SCAN_INTERVAL_MS 100
#define SVT_BLE_SCAN_WINDOW_MS   60

// ---- WEB и связь с телефоном ----
// 1 = точка доступа отвечает на проверки связи (DNS на адрес платы, /generate_204 и др.),
// чтобы телефон не считал сеть "без интернета", не отключался от неё и не открывал страницы через мобильную сеть
#define SVT_FAKE_INTERNET 1
// Журнал запросов WEB в Serial0: 0 нет, 1 все кроме опроса /api/meters, 2 все
#define SVT_WEB_LOG 1

// ---- Тревоги ----
// 1 = при показе тревоги или напоминания одна кнопка подтверждает текущую (UP+DOWN вместе: все);
// 0 = подтверждение только UP+DOWN вместе, одиночные кнопки продолжают переключать счётчики
#define SVT_ACK_SINGLE_BUTTON 1

// ---- LCD5110 ----
#define LCD_CONTRAST 52  // фон виден: уменьшать на 2-3; бледный текст: увеличивать

// ---- Цветной TFT (ST7735 1.77" 160x128 или ST7789) ----
#ifndef TFT_ROTATION   // плата со встроенным дисплеем задаёт поворот сама
  #define TFT_ROTATION 1   // 1 = альбомная 160x128; 0 = книжная 128x160; 3 = альбомная вверх ногами; 2 = книжная вверх ногами
#endif

// ST7735 1.77" (128x160): тип инициализации. Если цвета неверные или картинка смещена,
// на краю шум или полоса:
// INITR_BLACKTAB, INITR_GREENTAB, INITR_REDTAB, INITR_144GREENTAB, INITR_MINI160x80
#define ST7735_INIT INITR_BLACKTAB

// ST7789: размер матрицы (240x240, 240x320, 135x240)
#ifndef ST7789_W        // плата со встроенным дисплеем задаёт размер сама
  #define ST7789_W 240
  #define ST7789_H 240
#endif
